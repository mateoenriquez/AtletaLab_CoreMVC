CREATE TABLE roles (
    id INTEGER PRIMARY KEY AUTOINCREMENT, code VARCHAR(20) NOT NULL UNIQUE, name VARCHAR(50) NOT NULL UNIQUE, description VARCHAR(200),
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE archetypes (
    id INTEGER PRIMARY KEY AUTOINCREMENT, code VARCHAR(20) NOT NULL UNIQUE, name VARCHAR(50) NOT NULL UNIQUE,
    incPercentage DECIMAL(5,2) NOT NULL, stagnationPenalty DECIMAL(5,2) NOT NULL, deloadPercentage DECIMAL(5,2) NOT NULL,
    maxFatigueThreshold DECIMAL(8,2) NOT NULL, rpeLimit DECIMAL(3,1) NOT NULL,
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE users (
    id INTEGER PRIMARY KEY AUTOINCREMENT, email VARCHAR(200) NOT NULL UNIQUE, firstName VARCHAR(50) NOT NULL, lastName VARCHAR(50) NOT NULL,
    password VARCHAR(200) NOT NULL, birthDate DATE NOT NULL, roleId INTEGER NOT NULL REFERENCES roles(id), archetypeId INTEGER REFERENCES archetypes(id),
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE objectives (
    id INTEGER PRIMARY KEY AUTOINCREMENT, code VARCHAR(20) NOT NULL UNIQUE, name VARCHAR(50) NOT NULL,
    targetRepMin INTEGER NOT NULL, targetRepMax INTEGER NOT NULL, minSuccessRate DECIMAL(5,2) NOT NULL,
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CHECK (targetRepMax >= targetRepMin)
);
CREATE TABLE exercises (
    id INTEGER PRIMARY KEY AUTOINCREMENT, code VARCHAR(20) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL, muscleGroup VARCHAR(20) NOT NULL,
    fatigueCoefficient DECIMAL(4,2) NOT NULL, description VARCHAR(200),
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE routines (
    id INTEGER PRIMARY KEY AUTOINCREMENT, code VARCHAR(20) NOT NULL UNIQUE, title VARCHAR(100) NOT NULL, description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'Activa', athleteId INTEGER NOT NULL REFERENCES users(id), trainerId INTEGER NOT NULL REFERENCES users(id),
    objectiveId INTEGER NOT NULL REFERENCES objectives(id), effectivenessScore DECIMAL(5,2) DEFAULT 0.00, isBestPractice BOOLEAN DEFAULT 0,
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP, CHECK (athleteId <> trainerId)
);
CREATE TABLE routine_exercises (
    id INTEGER PRIMARY KEY AUTOINCREMENT, targetSets INTEGER NOT NULL, targetReps INTEGER NOT NULL, currentWeight DECIMAL(6,2) NOT NULL,
    projectedWeight DECIMAL(6,2) NOT NULL, routineId INTEGER NOT NULL REFERENCES routines(id) ON DELETE CASCADE, exerciseId INTEGER NOT NULL REFERENCES exercises(id)
);
CREATE TABLE workout_logs (
    id INTEGER PRIMARY KEY AUTOINCREMENT, setsCompleted INTEGER NOT NULL, repsAchieved INTEGER NOT NULL, weightUsed DECIMAL(6,2) NOT NULL,
    rpe DECIMAL(3,1) NOT NULL, loggedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP, routineExerciseId INTEGER NOT NULL REFERENCES routine_exercises(id) ON DELETE CASCADE
);
